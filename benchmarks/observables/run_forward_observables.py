#!/usr/bin/env python
"""Forward-observable benchmark: EIS, OCV-vs-SOC, dQ/dV and GITT-D.

    .venv/bin/python benchmarks/observables/run_forward_observables.py \
        --out results/observables

    .venv/bin/python -o addopts='' -m benchmark \
        benchmarks/observables/run_forward_observables.py

All inputs are verified installed PyBaMM 26.8.0.0 APIs and the installed
``Chen2020`` parameter set. Outputs are model-generated (SYNTHETIC ONLY):
they demonstrate observable extraction, not identifiability or real-data fit.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

from pybamm_closed_loop.pybamm_engine.observables import (  # noqa: E402
    compute_eis,
    compute_ocv_vs_soc,
    dqdv_from_solution,
    gitt_relaxation_summary,
    run_gitt_d,
    verified_api_signatures,
)

PARAMETER_SET = "Chen2020"
PINNED_PYBAMM_VERSION = "26.8.0.0"
DEFAULT_OUT = Path(__file__).resolve().parents[2] / "results" / "observables"

LIMITATIONS = [
    "SYNTHETIC ONLY: every curve is generated by the model, not measured experimentally.",
    "A successful fit to any observable is NOT proof of parameter identifiability.",
    "dQ/dV is finite-difference post-processing and is sensitive to noise; no smoothing is applied.",
    "GITT relaxation voltages are end-of-rest samples, not extrapolation to infinite time.",
    "PyBaMM 26.8.0.0 has no dedicated OCV-vs-SOC or GITT API; see docs/FORWARD_OBSERVABLES.md.",
]


def run_all(out_dir: Path) -> dict:
    """Generate all four observables and write arrays + provenance manifest."""
    import pybamm

    if pybamm.__version__ != PINNED_PYBAMM_VERSION:
        raise RuntimeError(
            f"pinned pybamm {PINNED_PYBAMM_VERSION} required, found {pybamm.__version__}"
        )
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    pv = pybamm.ParameterValues(PARAMETER_SET)

    eis = compute_eis("SPM", pv, np.logspace(-2, 2, 20), initial_soc=0.5)
    ocv = compute_ocv_vs_soc(pv, np.linspace(0.0, 1.0, 101))
    discharge = pybamm.Experiment(["Discharge at 1C for 600 s"], period="30 s")
    sim = pybamm.Simulation(
        pybamm.lithium_ion.SPM(), parameter_values=pv, experiment=discharge
    )
    dqdv = dqdv_from_solution(sim.solve())
    gitt = run_gitt_d(
        pv,
        current_A=0.5,
        pulse_duration_s=120.0,
        rest_duration_s=180.0,
        n_pulses=5,
        period_s=30.0,
    )
    relaxation = gitt_relaxation_summary(gitt)

    arrays = {
        "eis__frequency_Hz": eis.frequencies_Hz,
        "eis__z_re_Ohm": eis.z_re_Ohm,
        "eis__z_im_Ohm": eis.z_im_Ohm,
        "ocv_soc__soc": ocv.soc,
        "ocv_soc__ocv_V": ocv.ocv_V,
        "ocv_soc__x_negative": ocv.x_negative,
        "ocv_soc__y_positive": ocv.y_positive,
        "dqdv__capacity_Ah": dqdv.capacity_Ah,
        "dqdv__voltage_V": dqdv.voltage_V,
        "dqdv__dqdv_Ah_per_V": dqdv.dqdv_Ah_per_V,
        "gitt_d__time_s": gitt.time_s,
        "gitt_d__voltage_V": gitt.voltage_V,
        "gitt_d__current_A": gitt.current_A,
        "gitt_d__capacity_Ah": gitt.capacity_Ah,
        "gitt_d__titration_index": gitt.titration_index,
    }
    np.savez_compressed(out / "observables_arrays.npz", **arrays)

    manifest = {
        "label": "SYNTHETIC FORWARD-OBSERVABLE DEMONSTRATION",
        "pybamm_version": pybamm.__version__,
        "parameter_set": PARAMETER_SET,
        "model": "SPM",
        "protocol": {
            "eis": {
                "frequencies_Hz": "np.logspace(-2, 2, 20)",
                "initial_soc": 0.5,
                "surface_form": "differential",
            },
            "ocv_soc": {"soc": "np.linspace(0, 1, 101)", "eSOH direction": None},
            "dqdv": {"step": "Discharge at 1C for 600 s", "period": "30 s"},
            "gitt_d": {
                "current_A": 0.5,
                "pulse_duration_s": 120.0,
                "rest_duration_s": 180.0,
                "n_pulses": 5,
                "period_s": 30.0,
                "steps": gitt.metadata["steps"],
            },
        },
        "randomness": {
            "seed": None,
            "note": "No stochastic sampling: all protocols and grids are deterministic.",
        },
        "shapes": {name: list(arr.shape) for name, arr in arrays.items()},
        "gitt_d_relaxation_summary": relaxation,
        "verified_api_signatures": verified_api_signatures(),
        "observable_metadata": {
            "eis": eis.metadata,
            "ocv_soc": ocv.metadata,
            "dqdv": dqdv.metadata,
            "gitt_d": {
                k: v
                for k, v in gitt.metadata.items()
                if k != "soc_estimate_from_capacity"
            },
        },
        "limitations": LIMITATIONS,
    }
    (out / "run_manifest.json").write_text(
        json.dumps(manifest, indent=2, default=str), encoding="utf-8"
    )
    return manifest


@pytest.mark.benchmark
@pytest.mark.slow
def test_forward_observables_benchmark():
    """Benchmark entry point: generate every observable and record outputs."""
    manifest = run_all(DEFAULT_OUT)
    arrays = np.load(DEFAULT_OUT / "observables_arrays.npz")
    assert manifest["pybamm_version"] == PINNED_PYBAMM_VERSION
    assert manifest["label"].startswith("SYNTHETIC")
    assert arrays["eis__frequency_Hz"].shape == (20,)
    assert arrays["ocv_soc__ocv_V"].shape == (101,)
    assert arrays["dqdv__dqdv_Ah_per_V"].shape == arrays["dqdv__capacity_Ah"].shape
    assert set(int(i) for i in arrays["gitt_d__titration_index"] if i >= 0) == {
        0, 1, 2, 3, 4
    }
    assert (DEFAULT_OUT / "run_manifest.json").exists()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    manifest = run_all(args.out)
    print(f"Wrote forward-observable artifacts to {args.out}")
    print(f"  label: {manifest['label']}")
    print(f"  pybamm: {manifest['pybamm_version']}, parameter set: {manifest['parameter_set']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
