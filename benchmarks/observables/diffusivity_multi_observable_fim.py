def load_config(path: Path) -> dict[str, Any]:
    return yaml.safe_load(Path(path).read_text(encoding="utf-8"))


def parse_logspace(spec: str) -> np.ndarray:
    """Parse a deterministic ``logspace(start, stop, n)`` config string."""
    text = str(spec).strip()
    if not (text.startswith("logspace(") and text.endswith(")")):
        raise ValueError(f"expected 'logspace(start, stop, n)', got {spec!r}")
    parts = [p.strip() for p in text[len("logspace(") : -1].split(",")]
    if len(parts) != 3:
        raise ValueError(f"logspace needs 3 arguments, got {spec!r}")
    start, stop = float(parts[0]), float(parts[1])
    n = int(parts[2])
    if n < 1:
        raise ValueError(f"logspace n must be >= 1, got {n}")
    return np.logspace(start, stop, n)


def voltage_query_times(t_end_s: float, n_points: int, t_start_s: float) -> np.ndarray:
    """Sampling grid for a galvanostatic voltage curve (committed convention)."""
    if t_end_s <= t_start_s:
        raise ValueError(f"t_end_s ({t_end_s}) must exceed t_start_s ({t_start_s})")
    if n_points < 2:
        raise ValueError("n_points must be >= 2")
    return np.linspace(float(t_start_s), float(t_end_s), int(n_points))


def characteristic_scale(y0: Any, convention: str) -> float:
    """Characteristic magnitude used to non-dimensionalize an observable."""
    array = np.asarray(y0, dtype=float).reshape(-1)
    if array.size == 0:
        raise ValueError("empty observable vector")
    if convention == "std":
        value = float(np.std(array))
    elif convention == "mean_magnitude":
        value = float(np.mean(np.abs(array)))
    else:
        raise ValueError(f"unknown normalization convention {convention!r}")
    if not np.isfinite(value) or value <= 1e-12:
        raise ValueError(
            "observable has no resolvable variation at the baseline point "
            f"(scale={value!r}); refusing to normalize by a near-zero scale"
        )
    return value


def mean_abs_normalized_sensitivity(
    jacobian: np.ndarray, x: np.ndarray, y_scale: float
) -> float:
    """Mean |S| over the observation points for the (single) study parameter."""
    scaled = normalized_sensitivity(jacobian, np.asarray(x, dtype=float), y_scale)
    if scaled.size == 0:
        raise ValueError("empty sensitivity block")
    return float(np.abs(scaled).mean())


def implied_relative_standard_error(fim: np.ndarray) -> float:
    """FIM-implied relative standard error of a unit-mean scale factor.

    ``FIM = JᵀJ`` for a dimensionless scale factor with ``x = 1``; the
    Cramér–Rao lower bound gives ``SE = 1/sqrt(FIM)``, so the relative
    standard error is ``1/sqrt(FIM)``. ``inf`` means no information.
    """
    fim = np.asarray(fim, dtype=float)
    if fim.ndim != 2 or fim.shape[0] != fim.shape[1]:
        raise ValueError(f"FIM must be square, got {fim.shape}")
    if fim.shape != (1, 1):
        raise ValueError("relative standard error is defined here for one parameter")
    value = float(fim[0, 0])
    if value <= 0 or not np.isfinite(value):
        return float("inf")
    return float(1.0 / np.sqrt(value))


def classify_observability(mean_abs_s: float, rel_std: float) -> str:
    """Apply the recorded observability rules to one diagnostic block.

    A block is OBSERVABLE only when the recorded mean-|S| rule **and** the
    recorded relative-std rule are both satisfied; either failure means the
    observation set does not pin the parameter well enough to say otherwise.
    """
    if not np.isfinite(mean_abs_s):
        return "UNOBSERVABLE"
    if mean_abs_s < SENSITIVITY_OBSERVABILITY_THRESHOLD:
        return "UNOBSERVABLE"
    if not np.isfinite(rel_std) or rel_std > RELATIVE_STD_OBSERVABILITY_THRESHOLD:
        return "UNOBSERVABLE"
    return "OBSERVABLE"


def classify_information(rel_std: float, strongest_mean_abs_s: float) -> str:
    """Apply a conservative conjunction of the recorded observability rules.

    Two recorded rules exist: the per-protocol mean |S| rule
    (:data:`SENSITIVITY_OBSERVABILITY_THRESHOLD`) and the bootstrap relative
    standard-error rule (:data:`RELATIVE_STD_OBSERVABILITY_THRESHOLD`). The
    per-protocol rule does not aggregate meaningfully across observables with
    different units and noise levels, so for a *combined* observation set we
    require **both**:

    * the combined FIM's implied relative standard error meets the recorded
      information threshold, and
    * at least one contributing observable individually clears the recorded
      mean-|S| threshold.

    This aggregation is declared before looking at the numbers and can only
    make a verdict flip harder, never easier: stacking low-sensitivity
    observables cannot turn UNOBSERVABLE into OBSERVABLE on its own.
    """
    if not np.isfinite(rel_std) or rel_std > RELATIVE_STD_OBSERVABILITY_THRESHOLD:
        return "UNOBSERVABLE"
    if not np.isfinite(strongest_mean_abs_s):
        return "UNOBSERVABLE"
    if strongest_mean_abs_s < SENSITIVITY_OBSERVABILITY_THRESHOLD:
        return "UNOBSERVABLE"
    return "OBSERVABLE"


def compare_voltage_block_to_baseline(
    reproduced: float, baseline: float, tolerance: float
) -> dict[str, Any]:
    """Check that this study reproduces a committed voltage-only value."""
    delta = float(reproduced) - float(baseline)
    return {
        "reproduced_mean_abs_normalized_sensitivity": float(reproduced),
        "baseline_mean_abs_normalized_sensitivity": float(baseline),
        "absolute_delta": delta,
        "tolerance": float(tolerance),
        "within_tolerance": bool(abs(delta) <= float(tolerance)),
    }


def information_ratio(fim_augmented: np.ndarray, fim_voltage_only: np.ndarray) -> float:
    """sqrt(FIM_aug / FIM_vol) = factor by which the standard error shrinks."""
    a = float(np.asarray(fim_augmented, dtype=float).squeeze())
    v = float(np.asarray(fim_voltage_only, dtype=float).squeeze())
    if v <= 0 or not np.isfinite(v):
        return float("inf")
    if a < 0 or not np.isfinite(a):
        return float("inf")
    return float(np.sqrt(a / v))


def diffusion_frequency(diffusivity: float, particle_radius: float) -> dict[str, Any]:
    """A-priori solid-diffusion time constant and characteristic frequency.

    Pure arithmetic on two values read from the installed parameter set; no
    value is invented. ``tau = R^2 / D`` and ``f = 1 / (2*pi*tau)`` are the
    standard spherical-diffusion scales used to choose an EIS band *before*
    looking at any sensitivity.
    """
    if diffusivity <= 0 or particle_radius <= 0:
        raise ValueError("diffusivity and particle_radius must be positive")
    tau = float(particle_radius) ** 2 / float(diffusivity)
    return {
        "diffusivity_m2_s": float(diffusivity),
        "particle_radius_m": float(particle_radius),
        "diffusion_time_constant_s": tau,
        "diffusion_frequency_Hz": 1.0 / (2.0 * np.pi * tau),
    }


def relative_change(reference: Any, perturbed: Any) -> float:
    """max|Δ| / max|reference| for two equal-length vectors."""
    a = np.asarray(reference, dtype=float).reshape(-1)
    b = np.asarray(perturbed, dtype=float).reshape(-1)
    if a.shape != b.shape:
        raise ValueError(f"shape mismatch: {a.shape} vs {b.shape}")
    peak = float(np.max(np.abs(a)))
    if peak <= 0:
        return float("inf")
    return float(np.max(np.abs(b - a)) / peak)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 16), b""):
            digest.update(chunk)
    return digest.hexdigest()


