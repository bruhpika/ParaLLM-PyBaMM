def run_joint_fim(
    cfg: dict[str, Any],
    blocks: dict[str, dict[str, Any]],
    eis_sigma: float,
    config_path: Path,
) -> dict[str, Any] | None:
    """Joint three-parameter FIM: D_neg, j0_neg and D_e free together.

    Answers the question the single-parameter study cannot: does the low-SOC
    GITT-D information about D_neg survive when the negative kinetics and the
    electrolyte diffusivity are also free? Report-only; no fit is performed.
    """
    import pybamm

    if pybamm.__version__ != PINNED_PYBAM_VERSION:
        raise RuntimeError(
            f"pinned pybamm {PINNED_PYBAM_VERSION} required, found {pybamm.__version__}"
        )

    jcfg = cfg.get("joint_fim")
    if not jcfg or not jcfg.get("enabled", False):
        return None

    t0 = time.perf_counter()
    parameter_set = str(cfg["parameter_set"])
    model_name = str(cfg["model_name"])
    study_parameter = str(cfg["parameter"])
    rel = float(jcfg["rel_perturbation"])
    if rel <= 0 or not np.isfinite(rel):
        raise ValueError(f"joint rel_perturbation must be positive, got {rel!r}")
    collinearity_threshold = float(jcfg["collinearity_warning_abs_correlation"])
    if not 0.0 < collinearity_threshold <= 1.0:
        raise ValueError(
            "collinearity_warning_abs_correlation must be in (0, 1], got "
            f"{collinearity_threshold!r}"
        )

    parameter_records: list[dict[str, Any]] = []
    labels: list[str] = []
    names: list[str] = []
    pv0 = pybamm.ParameterValues(parameter_set)
    for entry in jcfg["parameters"]:
        label = str(entry["label"])
        name = str(entry["name"])
        if label in labels:
            raise ValueError(f"duplicate joint parameter label {label!r}")
        if name in names:
            raise ValueError(f"duplicate joint parameter name {name!r}")
        if name not in pv0.keys():
            raise KeyError(
                f"joint parameter {name!r} is not in the installed {parameter_set} set; "
                "refusing to invent or substitute a value"
            )
        value = pv0[name]
        parameter_records.append(
            {
                "label": label,
                "name": name,
                "kind": "function-valued" if callable(value) else "scalar",
                "baseline_value": None if callable(value) else float(value),
            }
        )
        labels.append(label)
        names.append(name)
    if not parameter_records:
        raise ValueError("joint_fim.parameters must not be empty")
    if study_parameter not in names:
        raise ValueError(
            f"study parameter {study_parameter!r} must be one of the joint parameters"
        )
    primary_label = labels[names.index(study_parameter)]

    selected = [str(name) for name in jcfg["observables"]]
    if not selected:
        raise ValueError("joint_fim.observables must not be empty")
    if len(set(selected)) != len(selected):
        raise ValueError("joint_fim.observables contains duplicates")
    specs = joint_observable_specs(cfg, model_name, float(eis_sigma))
    unknown = [name for name in selected if name not in specs]
    if unknown:
        raise KeyError(f"unknown joint observables {unknown!r}")

    x = np.ones(len(names), dtype=float)

    def build_joint_blocks(
        rel_step: float,
    ) -> tuple[dict[str, dict[str, Any]], dict[str, dict[str, float]]]:
        blocks_for_step: dict[str, dict[str, Any]] = {}
        sensitivity_for_step: dict[str, dict[str, float]] = {}
        for name in selected:
            spec = specs[name]
            jacobian, y_scale = _joint_jacobian_for(
                spec["predict"],
                parameter_set,
                names,
                rel_step,
                x,
                str(spec["normalization"]),
            )
            blocks_for_step[name] = {
                # Same FIM convention as ``_block`` (2026-11-27 correction):
                # raw sensitivities against noise in observable units; the
                # ``y_scale``-normalized sensitivities are used only for the
                # dimensionless mean-|S| rule.
                "jacobian": jacobian,
                "sigma": float(spec["sigma"]),
                "y_scale": 1.0,
            }
            scaled = normalized_sensitivity(jacobian, x, y_scale)
            sensitivity_for_step[name] = {
                label: float(np.abs(scaled[:, index]).mean())
                for index, label in enumerate(labels)
            }
        return blocks_for_step, sensitivity_for_step

    joint_blocks, per_observable = build_joint_blocks(rel)

    # Cross-check: the D_neg column must reproduce the single-parameter block
    # (same protocol, same normalization, same FD step). A mismatch means the
    # two constructions have drifted apart and the joint result cannot be
    # compared with the committed study.
    cross_checks: dict[str, Any] = {}
    consistent = True
    primary_index = labels.index(primary_label)
    for name in selected:
        if name not in blocks:
            continue
        single = float(blocks[name]["mean_abs_normalized_sensitivity"])
        joint = float(per_observable[name][primary_label])
        delta = abs(joint - single)
        tolerance = 1e-6 * max(abs(single), 1.0)
        ok = bool(delta <= tolerance)
        cross_checks[name] = {
            "single_parameter_mean_abs_normalized_sensitivity": single,
            "joint_column_mean_abs_normalized_sensitivity": joint,
            "absolute_delta": delta,
            "tolerance": tolerance,
            "within_tolerance": ok,
        }
        consistent = consistent and ok
    cross_check_block = {
        "parameter": study_parameter,
        "checks": cross_checks,
        "all_within_tolerance": consistent,
        "note": (
            "The primary-parameter column of the joint Jacobian is compared with "
            "the single-parameter block on the same observable. Identity confirms "
            "that both studies use the same protocol and normalization."
        ),
    }
    if not consistent:
        raise RuntimeError(
            "joint FIM D_neg column does not reproduce the single-parameter blocks: "
            f"{cross_check_block}"
        )

    def summarize_set(
        names_in_set: list[str],
        blocks_for_set: dict[str, dict[str, Any]],
        sensitivity_for_set: dict[str, dict[str, float]],
    ) -> dict[str, Any]:
        combined = multi_observable_fim(
            {name: blocks_for_set[name] for name in names_in_set}, x
        )
        fim = np.asarray(combined["fim"], dtype=float)
        marginal = marginal_relative_standard_errors(fim)
        correlation = parameter_correlation_matrix(fim)
        per_parameter: dict[str, Any] = {}
        for index, label in enumerate(labels):
            strongest = max(sensitivity_for_set[name][label] for name in names_in_set)
            per_parameter[label] = {
                "marginal_relative_standard_error": float(marginal[index]),
                "strongest_mean_abs_normalized_sensitivity": float(strongest),
                "classification": classify_observability(
                    float(strongest), float(marginal[index])
                ),
                "per_observable_mean_abs_normalized_sensitivity": {
                    name: sensitivity_for_set[name][label] for name in names_in_set
                },
            }
        return {
            "observables": names_in_set,
            "fim": fim.tolist(),
            "rank": int(np.linalg.matrix_rank(fim)),
            "n_parameters": int(fim.shape[0]),
            "condition_number": float(combined["condition_number"]),
            "eigenvalues": [float(v) for v in combined["eigenvalues"]],
            "correlation": correlation.tolist(),
            "per_parameter": per_parameter,
        }

    voltage_names = [n for n in selected if n.startswith("voltage_")]
    gitt_names = [n for n in selected if n.startswith("gitt_d_")]
    eis_names = [n for n in selected if n.startswith("eis_")]
    voltage_gitt_names = [n for n in selected if n in set(voltage_names) | set(gitt_names)]
    sets: dict[str, Any] = {}
    for set_name, set_names in (
        ("voltage_only", voltage_names),
        ("gitt_only", gitt_names),
        ("voltage_plus_gitt", voltage_gitt_names),
        ("eis_only", eis_names),
        ("all_configured", selected),
    ):
        if set_names:
            sets[set_name] = summarize_set(
                set_names, joint_blocks, per_observable
            )

    augmented = sets["all_configured"]

    voltage_set = sets.get("voltage_only")
    if voltage_set is not None:
        voltage_strongest = voltage_set["per_parameter"][primary_label][
            "strongest_mean_abs_normalized_sensitivity"
        ]
        interpretation = (
            "Marginal standard errors are local Cramér–Rao bounds conditional on "
            "the declared i.i.d. noise. The OBSERVABLE/UNOBSERVABLE label is the "
            "declared conjunction: marginal relative SE <= "
            f"{RELATIVE_STD_OBSERVABILITY_THRESHOLD:g} AND at least one contributing "
            f"observable has mean |S| >= {SENSITIVITY_OBSERVABILITY_THRESHOLD:g}. "
            "The voltage-only set meets the SE limb but not the |S| limb "
            f"(strongest {voltage_strongest:.4g}), so it stays UNOBSERVABLE even "
            "though its implied SE is small. The flip is therefore a conservative "
            "classification flip, not a claim that voltage data are uninformative."
        )
    else:
        interpretation = (
            "Marginal standard errors are local Cramér–Rao bounds conditional on "
            "the declared i.i.d. noise; classifications additionally require at "
            "least one contributing observable to clear the recorded mean-|S| rule."
        )

    # Single-parameter reference computed from the same joint Jacobians: this
    # isolates the cost of freeing the other two parameters.
    single_parameter: dict[str, Any] = {}
    for index, label in enumerate(labels):
        one = multi_observable_fim(
            {
                name: {
                    "jacobian": joint_blocks[name]["jacobian"][:, [index]],
                    "sigma": joint_blocks[name]["sigma"],
                    "y_scale": joint_blocks[name]["y_scale"],
                }
                for name in selected
            },
            np.array([1.0]),
        )
        single_parameter[label] = {
            "relative_standard_error": implied_relative_standard_error(one["fim"]),
            "fim": float(np.asarray(one["fim"]).squeeze()),
        }

    primary_correlations = [
        {
            "parameter": label,
            "correlation": float(augmented["correlation"][primary_index][index]),
        }
        for index, label in enumerate(labels)
        if label != primary_label
    ]
    collinear_with = [
        entry
        for entry in primary_correlations
        if abs(entry["correlation"]) >= collinearity_threshold
    ]
    primary_summary = dict(augmented["per_parameter"][primary_label])
    single_se = single_parameter[primary_label]["relative_standard_error"]
    joint_se = float(primary_summary["marginal_relative_standard_error"])
    primary_summary.update(
        {
            "single_parameter_relative_standard_error": single_se,
            "variance_inflation_factor": variance_inflation_factor(joint_se, single_se),
            "correlations": primary_correlations,
            "collinear_with": collinear_with,
            "collinearity_warning_abs_correlation": collinearity_threshold,
            "survives_collinearity_check": bool(
                primary_summary["classification"] == "OBSERVABLE"
                and not collinear_with
            ),
        }
    )

    # ---- finite-difference step robustness --------------------------------
    nominal_se = {
        label: float(
            augmented["per_parameter"][label]["marginal_relative_standard_error"]
        )
        for label in labels
    }
    nominal_corr = np.asarray(augmented["correlation"], dtype=float)
    robustness_checks: list[dict[str, Any]] = []
    for step in (float(v) for v in jcfg.get("robustness_rel_perturbations", [])):
        if step <= 0 or not np.isfinite(step):
            raise ValueError(
                f"robustness rel_perturbation must be positive, got {step!r}"
            )
        if np.isclose(step, rel):
            continue
        step_blocks, step_sensitivity = build_joint_blocks(step)
        combined = multi_observable_fim(
            {name: step_blocks[name] for name in selected}, x
        )
        fim = np.asarray(combined["fim"], dtype=float)
        marginal = marginal_relative_standard_errors(fim)
        correlation = parameter_correlation_matrix(fim)
        strongest = max(
            step_sensitivity[name][primary_label] for name in selected
        )
        robustness_checks.append(
            {
                "rel_perturbation": step,
                "primary_relative_standard_error": float(marginal[primary_index]),
                "primary_classification": classify_observability(
                    float(strongest), float(marginal[primary_index])
                ),
                "marginal_relative_standard_errors": {
                    label: float(marginal[index])
                    for index, label in enumerate(labels)
                },
                "correlations_with_primary": {
                    label: float(correlation[primary_index][index])
                    for index, label in enumerate(labels)
                    if label != primary_label
                },
                "condition_number": float(combined["condition_number"]),
            }
        )
    if robustness_checks:
        max_se_deviation = max(
            (
                abs(
                    check["marginal_relative_standard_errors"][label]
                    / nominal_se[label]
                    - 1.0
                )
                for check in robustness_checks
                for label in labels
                if np.isfinite(nominal_se[label]) and nominal_se[label] > 0
            ),
            default=0.0,
        )
        max_corr_deviation = max(
            (
                abs(
                    check["correlations_with_primary"][label]
                    - nominal_corr[primary_index][labels.index(label)]
                )
                for check in robustness_checks
                for label in labels
                if label != primary_label
            ),
            default=0.0,
        )
        perturbation_robustness = {
            "nominal_rel_perturbation": rel,
            "checks": robustness_checks,
            "classification_stable": all(
                check["primary_classification"] == primary_summary["classification"]
                for check in robustness_checks
            ),
            "max_relative_se_deviation": float(max_se_deviation),
            "max_abs_correlation_deviation": float(max_corr_deviation),
        }
    else:
        perturbation_robustness = {
            "nominal_rel_perturbation": rel,
            "checks": [],
            "classification_stable": None,
            "max_relative_se_deviation": None,
            "max_abs_correlation_deviation": None,
        }

    voltage_se = (
        sets["voltage_only"]["per_parameter"][primary_label][
            "marginal_relative_standard_error"
        ]
        if "voltage_only" in sets
        else float("inf")
    )
    gitt_se = (
        sets["gitt_only"]["per_parameter"][primary_label][
            "marginal_relative_standard_error"
        ]
        if "gitt_only" in sets
        else float("inf")
    )
    primary_summary["joint_voltage_only_relative_standard_error"] = voltage_se
    primary_summary["joint_gitt_only_relative_standard_error"] = gitt_se
    primary_summary["joint_information_gain_over_voltage_only"] = (
        standard_error_reduction(voltage_se, joint_se)
    )

    if primary_summary["survives_collinearity_check"]:
        statement = (
            f"{primary_label} remains marginally observable in the joint "
            f"{len(labels)}-parameter fit and no free parameter is correlated "
            f"above |rho| = {collinearity_threshold:g}."
        )
    elif primary_summary["classification"] == "OBSERVABLE":
        statement = (
            f"{primary_label} is marginally observable in the joint fit, but it is "
            f"collinear above |rho| = {collinearity_threshold:g} with "
            f"{', '.join(entry['parameter'] for entry in collinear_with)}; the "
            "observable set does not separate them, so this is not a calibration "
            "recommendation."
        )
    else:
        statement = (
            f"{primary_label} does not survive the joint {len(labels)}-parameter "
            "fit under the declared rules; the single-parameter result was "
            "conditional on the other parameters being fixed."
        )
    verdict = {
        "primary_parameter": primary_label,
        "classification": primary_summary["classification"],
        "survives_collinearity_check": primary_summary["survives_collinearity_check"],
        "statement": statement,
        "decision": "unchanged",
    }

    out_report = REPO_ROOT / str(jcfg["outputs"]["report"])
    out_summary = REPO_ROOT / str(jcfg["outputs"]["summary"])
    out_report.parent.mkdir(parents=True, exist_ok=True)

    report: dict[str, Any] = {
        "label": "SYNTHETIC JOINT MULTI-PARAMETER FIM DIAGNOSTIC",
        "run_id": f"{cfg['run_id']}_joint",
        "description": (
            "Joint finite-difference FIM over the declared parameter subset, "
            "comparing voltage-only, GITT-only and combined observable sets. "
            "Diagnostic only."
        ),
        "diagnostic_only": True,
        "decision_changed": False,
        "registry_write": False,
        "parameter_set": parameter_set,
        "model_name": model_name,
        "study_parameter": study_parameter,
        "primary_parameter": primary_label,
        "rel_perturbation": rel,
        "parameters": parameter_records,
        "observables": selected,
        "thresholds": {
            "sensitivity_observability": SENSITIVITY_OBSERVABILITY_THRESHOLD,
            "relative_std_observability": RELATIVE_STD_OBSERVABILITY_THRESHOLD,
            "collinearity_warning_abs_correlation": collinearity_threshold,
            "source": (
                "sensitivity and relative-SE rules from "
                "src/pybamm_closed_loop/assembly/observability.py; the collinearity "
                "threshold is a declared diagnostic convention"
            ),
        },
        "single_parameter_cross_check": cross_check_block,
        "fim_convention": (
            "FIM from raw sensitivities with noise in observable units "
            "(2026-11-27 unit correction, same as the single-parameter study); "
            "mean |S| keeps the recorded dimensionless convention."
        ),
        "observable_sets": sets,
        "single_parameter_reference": single_parameter,
        "primary_parameter_summary": primary_summary,
        "interpretation": interpretation,
        "perturbation_robustness": perturbation_robustness,
        "verdict": verdict,
        "environment": {
            "python": platform.python_version(),
            "pybamm": pybamm.__version__,
        },
        "config_sha256": _sha256(Path(config_path)),
        "limitations": JOINT_LIMITATIONS,
        "scientific_note": (
            "Local joint FIM diagnostic only. Freeing a parameter subset tests "
            "collinearity, not global identifiability (rule 7); all curves are "
            "synthetic (rule 8). No calibration objective, registry record or "
            "dossier decision was changed (rule 10)."
        ),
        "runtime_s": time.perf_counter() - t0,
    }
    out_report.write_text(json.dumps(report, indent=2), encoding="utf-8")
    out_summary.write_text(_render_joint_summary(report), encoding="utf-8")
    return report


def run_diagnostic(config_path: Path) -> dict[str, Any]:
    """Run the full diagnostic and write the committed artifacts."""
    import pybamm

    if pybamm.__version__ != PINNED_PYBAM_VERSION:
        raise RuntimeError(
            f"pinned pybamm {PINNED_PYBAM_VERSION} required, found {pybamm.__version__}"
        )

    cfg = load_config(config_path)
    rel = float(cfg["rel_perturbation"])
    if rel <= 0 or not np.isfinite(rel):
        raise ValueError(f"rel_perturbation must be finite and positive, got {rel!r}")

    parameter_set = str(cfg["parameter_set"])
    parameter = str(cfg["parameter"])
    model_name = str(cfg["model_name"])
    norms = cfg["normalization"]
    x = np.array([1.0])

    # Introspection guard: the study parameter must exist in the installed set.
    pv0 = pybamm.ParameterValues(parameter_set)
    if parameter not in pv0.keys():
        raise KeyError(
            f"study parameter {parameter!r} is not in the installed {parameter_set} set; "
            "refusing to invent or substitute a value"
        )
    baseline_value = pv0[parameter]
    if callable(baseline_value):
        raise TypeError(
            f"study parameter {parameter!r} is function-valued in {parameter_set}; "
            "this diagnostic expects a scalar (see configs/p2/diffusivity_feasibility.yaml)"
        )

    radius_key = "Negative particle radius [m]"
    if radius_key not in pv0.keys():
        raise KeyError(f"required verified key {radius_key!r} is absent")
    a_priori = diffusion_frequency(float(baseline_value), float(pv0[radius_key]))
    eis_band = parse_logspace(str(cfg["eis"]["frequencies_Hz"]))
    a_priori["eis_band_Hz"] = [float(eis_band.min()), float(eis_band.max())]
    a_priori["eis_band_covers_diffusion_frequency"] = bool(
        eis_band.min() <= a_priori["diffusion_frequency_Hz"] <= eis_band.max()
    )
    a_priori["source"] = (
        "installed Chen2020 values; tau = R^2/D, f = 1/(2*pi*tau)"
    )

    out_report = REPO_ROOT / str(cfg["outputs"]["report"])
    out_summary = REPO_ROOT / str(cfg["outputs"]["summary"])
    out_report.parent.mkdir(parents=True, exist_ok=True)

    t0 = time.perf_counter()
    blocks: dict[str, dict[str, Any]] = {}
    voltage_only: dict[str, dict[str, Any]] = {}

    # ---- voltage block: identical protocols/grids to the committed study ----
    for cond in cfg["voltage_conditions"]:
        name = f"voltage_{cond['name']}"
        t_query = voltage_query_times(
            float(cond["t_end_s"]),
            int(cfg["voltage_n_points"]),
            float(cfg["voltage_t_start_s"]),
        )
        jac, y_scale = _jacobian_for(
            lambda pv, steps=cond["steps"], t=t_query: voltage_curve(
                pv, model_name, steps, t
            ),
            parameter_set,
            parameter,
            rel,
            x,
            str(norms["voltage"]),
        )
        block = _block(
            name,
            jac,
            y_scale,
            float(cfg["noise"]["voltage_V"]),
            x,
            str(norms["voltage"]),
        )
        blocks[name] = block
        voltage_only[name] = block

    # ---- GITT-D blocks ----------------------------------------------------
    gitt_spec = cfg["gitt_d"]
    protocol_warnings = gitt_protocol_warnings(gitt_spec)
    gitt_protocol: dict[str, Any] = {
        "model_name": str(gitt_spec["model_name"]),
        "current_A": float(gitt_spec["current_A"]),
        "pulse_duration_s": float(gitt_spec["pulse_duration_s"]),
        "rest_duration_s": float(gitt_spec["rest_duration_s"]),
        "n_pulses": int(gitt_spec["n_pulses"]),
        "period_s": float(gitt_spec["period_s"]),
        "initial_soc": gitt_spec.get("initial_soc"),
        "relaxation_fit_points": int(gitt_spec.get("relaxation_fit_points", 5)),
    }
    capacity_key = "Nominal cell capacity [A.h]"
    if capacity_key in pv0.keys():
        capacity = float(pv0[capacity_key])
        gitt_protocol["cell_capacity_Ah"] = capacity
        gitt_protocol["current_C_rate"] = float(gitt_spec["current_A"]) / capacity
    feature_sigmas = gitt_feature_sigmas(
        gitt_spec, float(cfg["noise"]["gitt_voltage_V"])
    )
    gitt_protocol["feature_sigmas"] = feature_sigmas
    jac, y_scale = _jacobian_for(
        lambda pv, spec=gitt_spec: gitt_rest_voltages(pv, spec),
        parameter_set,
        parameter,
        rel,
        x,
        str(norms["gitt_rest_voltage"]),
    )
    blocks["gitt_d_rest_voltage"] = _block(
        "gitt_d_rest_voltage",
        jac,
        y_scale,
        feature_sigmas["gitt_rest_voltage"]["sigma"],
        x,
        str(norms["gitt_rest_voltage"]),
    )

    jac, y_scale = _jacobian_for(
        lambda pv, spec=gitt_spec: gitt_pulse_drops(pv, spec),
        parameter_set,
        parameter,
        rel,
        x,
        str(norms["gitt_pulse_drop"]),
    )
    blocks["gitt_d_pulse_drop"] = _block(
        "gitt_d_pulse_drop",
        jac,
        y_scale,
        feature_sigmas["gitt_pulse_drop"]["sigma"],
        x,
        str(norms["gitt_pulse_drop"]),
    )

    jac, y_scale = _jacobian_for(
        lambda pv, spec=gitt_spec: gitt_relaxation_slopes(pv, spec),
        parameter_set,
        parameter,
        rel,
        x,
        str(norms["gitt_relaxation_slope"]),
    )
    blocks["gitt_d_relaxation_slope"] = _block(
        "gitt_d_relaxation_slope",
        jac,
        y_scale,
        feature_sigmas["gitt_relaxation_slope"]["sigma"],
        x,
        str(norms["gitt_relaxation_slope"]),
    )

    # ---- EIS blocks -------------------------------------------------------
    eis_spec = cfg["eis"]
    pv_eis = scaled_parameter_values(parameter_set, parameter, 1.0)
    eis_reference = eis_spectrum(pv_eis, eis_spec, "z_re")
    eis_sigma = float(cfg["noise"]["eis_relative"]) * float(
        np.mean(np.abs(eis_reference))
    )
    if eis_sigma <= 0:
        raise ValueError(
            "EIS noise assumption resolves to a non-positive sigma; refusing to continue"
        )
    for name, component in (
        ("eis_re_impedance", "z_re"),
        ("eis_neg_im_impedance", "neg_z_im"),
    ):
        jac, y_scale = _jacobian_for(
            lambda pv, spec=eis_spec, comp=component: eis_spectrum(pv, spec, comp),
            parameter_set,
            parameter,
            rel,
            x,
            str(norms["eis"]),
        )
        blocks[name] = _block(
            name, jac, y_scale, eis_sigma, x, str(norms["eis"])
        )

    # ---- OCV-vs-SOC null control -----------------------------------------
    ocv_spec = cfg["ocv_soc"]
    jac, y_scale = _jacobian_for(
        lambda pv, spec=ocv_spec: ocv_curve(pv, spec),
        parameter_set,
        parameter,
        rel,
        x,
        str(norms["ocv"]),
    )
    blocks["ocv_soc_control"] = _block(
        "ocv_soc_control",
        jac,
        y_scale,
        float(cfg["noise"]["ocv_voltage_V"]),
        x,
        str(norms["ocv"]),
    )

    # ---- EIS propagation positive control --------------------------------
    control = cfg["positive_control"]
    control_parameter = str(control["parameter"])
    control_factor = float(control["factor"])
    if control_parameter not in pv0.keys():
        raise KeyError(
            f"positive-control parameter {control_parameter!r} is absent from {parameter_set}"
        )
    control_component = str(control["component"])
    base_spectrum = eis_spectrum(
        scaled_parameter_values(parameter_set, parameter, 1.0), eis_spec, control_component
    )
    control_spectrum = eis_spectrum(
        scaled_parameter_values(parameter_set, control_parameter, control_factor),
        eis_spec,
        control_component,
    )
    positive_control = {
        "parameter": control_parameter,
        "factor": control_factor,
        "component": control_component,
        "relative_impedance_change": relative_change(base_spectrum, control_spectrum),
        "interpretation": (
            "A non-zero relative change proves the EIS simulation applies supplied "
            "parameter values. A near-zero change for the study parameter is therefore "
            "a property of the installed EIS formulation, not a harness bug."
        ),
    }

    # ---- joint multi-parameter FIM (collinearity check) -------------------
    joint_report = run_joint_fim(cfg, blocks, eis_sigma, config_path)
    joint_block: dict[str, Any] | None = None
    if joint_report is not None:
        primary = joint_report["primary_parameter_summary"]
        joint_block = {
            "report": str(cfg["joint_fim"]["outputs"]["report"]),
            "summary": str(cfg["joint_fim"]["outputs"]["summary"]),
            "primary_parameter": joint_report["primary_parameter"],
            "parameters": [p["label"] for p in joint_report["parameters"]],
            "classification": primary["classification"],
            "marginal_relative_standard_error": primary[
                "marginal_relative_standard_error"
            ],
            "single_parameter_relative_standard_error": primary[
                "single_parameter_relative_standard_error"
            ],
            "variance_inflation_factor": primary["variance_inflation_factor"],
            "collinear_with": primary["collinear_with"],
            "survives_collinearity_check": primary["survives_collinearity_check"],
            "joint_condition_number": joint_report["observable_sets"][
                "all_configured"
            ]["condition_number"],
            "single_parameter_cross_check_passed": joint_report[
                "single_parameter_cross_check"
            ]["all_within_tolerance"],
            "classification_stable_across_fd_steps": joint_report[
                "perturbation_robustness"
            ]["classification_stable"],
            "max_relative_se_deviation_across_fd_steps": joint_report[
                "perturbation_robustness"
            ]["max_relative_se_deviation"],
            "statement": joint_report["verdict"]["statement"],
        }

    # ---- combine ----------------------------------------------------------
    def _combine(names: list[str]) -> dict[str, Any]:
        combined = multi_observable_fim(
            {n: blocks[n]["_block"] for n in names}, x
        )
        fim = np.asarray(combined["fim"], dtype=float)
        rel_std = implied_relative_standard_error(fim)
        mean_abs = {n: blocks[n]["mean_abs_normalized_sensitivity"] for n in names}
        strongest = float(max(mean_abs.values()))
        # The stacked mean |S| uses each block's own normalization, so the
        # combined verdict requires the combined information rule *and* at
        # least one block clearing the recorded per-observable sensitivity
        # rule. Stacking cannot manufacture a flip by itself.
        return {
            "observables": names,
            "fim": float(fim.squeeze()),
            "implied_relative_standard_error": rel_std,
            "classification": classify_information(rel_std, strongest),
            "strongest_block_mean_abs_normalized_sensitivity": strongest,
            "classification_rule": (
                "conjunction: combined implied rel. SE <= "
                f"{RELATIVE_STD_OBSERVABILITY_THRESHOLD} AND strongest block mean |S| >= "
                f"{SENSITIVITY_OBSERVABILITY_THRESHOLD}"
            ),
            "per_block_mean_abs_normalized_sensitivity": mean_abs,
            "condition_number": combined["condition_number"],
            "stacked_jacobian_shape": combined["stacked_jacobian_shape"],
        }

    voltage_names = list(voltage_only)
    augmented_names = voltage_names + [
        "gitt_d_rest_voltage",
        "gitt_d_pulse_drop",
        "gitt_d_relaxation_slope",
        "eis_re_impedance",
        "eis_neg_im_impedance",
    ]
    comparison = _combine(voltage_names)
    augmented = _combine(augmented_names)

    # ---- reproduce the committed voltage-only baseline -------------------
    baseline_path = REPO_ROOT / str(cfg["baseline_report"])
    baseline_block: dict[str, Any] = {
        "path": str(cfg["baseline_report"]),
        "source": None,
    }
    if baseline_path.exists():
        baseline = json.loads(baseline_path.read_text(encoding="utf-8"))
        tolerance = float(cfg["baseline_tolerance"])
        checks: dict[str, Any] = {}
        within = True
        for cond in cfg["voltage_conditions"]:
            key = cond["name"]
            committed = (
                baseline.get("per_condition", {})
                .get(key, {})
                .get("mean_abs_normalized_sensitivity", {})
                .get(parameter)
            )
            if committed is None:
                checks[key] = {
                    "status": "missing committed value",
                    "parameter": parameter,
                }
                within = False
                continue
            check = compare_voltage_block_to_baseline(
                blocks[f"voltage_{key}"]["mean_abs_normalized_sensitivity"],
                float(committed),
                tolerance,
            )
            checks[key] = check
            within = within and check["within_tolerance"]
        baseline_block.update(
            {
                "source": "results/p2/diffusivity_feasibility/report.json",
                "parameter": parameter,
                "checks": checks,
                "all_within_tolerance": within,
            }
        )
    else:
        baseline_block["note"] = (
            "committed baseline report absent; comparison skipped (not an error)"
        )

    information_gain = information_ratio(augmented["fim"], comparison["fim"])

    flipped = (
        comparison["classification"] == "UNOBSERVABLE"
        and augmented["classification"] == "OBSERVABLE"
    )
    if flipped:
        verdict_statement = (
            "The added observables flip the recorded UNOBSERVABLE verdict for this "
            "parameter under the declared aggregation rule."
        )
    else:
        verdict_statement = (
            "The added observables do NOT flip the recorded UNOBSERVABLE verdict "
            "under the declared aggregation rule; the parameter remains MEASURE, "
            "not CALIBRATE."
        )
    verdict = {
        "voltage_only_classification": comparison["classification"],
        "observable_augmented_classification": augmented["classification"],
        "flip": bool(flipped),
        "statement": verdict_statement,
        "decision": "unchanged",
    }

    report: dict[str, Any] = {
        "label": "SYNTHETIC OBSERVABLE-AUGMENTED IDENTIFIABILITY DIAGNOSTIC",
        "run_id": cfg["run_id"],
        "description": cfg.get("description", ""),
        "diagnostic_only": True,
        "decision_changed": False,
        "registry_write": False,
        "parameter": parameter,
        "parameter_set": parameter_set,
        "model_name": model_name,
        "baseline_parameter_value": float(baseline_value),
        "scale_factor": float(x[0]),
        "rel_perturbation": rel,
        "thresholds": {
            "sensitivity_observability": SENSITIVITY_OBSERVABILITY_THRESHOLD,
            "relative_std_observability": RELATIVE_STD_OBSERVABILITY_THRESHOLD,
            "source": "src/pybamm_closed_loop/assembly/observability.py (recorded rules)",
        },
        "fim_convention": (
            "FIM from raw sensitivities (observable units per unit scale factor) "
            "with noise in the same units, so implied relative SEs are true "
            "Cramér-Rao relative SEs of the unit-mean scale factor. mean |S| "
            "keeps the recorded dimensionless convention (y_scale-normalized). "
            "2026-11-27 correction of a unit mismatch in the first run."
        ),
        "a_priori_diffusion_scales": a_priori,
        "gitt_protocol": gitt_protocol,
        "protocol_warnings": protocol_warnings,
        "per_observable": {
            name: {k: v for k, v in block.items() if k != "_block"}
            for name, block in blocks.items()
        },
        "voltage_only": comparison,
        "observable_augmented": augmented,
        "information_gain_sqrt_ratio": information_gain,
        "standard_error_reduction_factor": information_gain,
        "verdict": verdict,
        "eis_positive_control": positive_control,
        "joint_fim": joint_block,
        "baseline_comparison": baseline_block,
        "environment": {
            "python": platform.python_version(),
            "pybamm": pybamm.__version__,
        },
        "verified_api_signatures": verified_api_signatures(),
        "config_sha256": _sha256(Path(config_path)),
        "limitations": LIMITATIONS,
        "scientific_note": (
            "Local sensitivity diagnostic only. A well-conditioned FIM is not proof "
            "of identifiability (rule 7) and all curves are synthetic (rule 8). No "
            "calibration objective, registry record or dossier decision was changed."
        ),
        "runtime_s": time.perf_counter() - t0,
    }

    out_report.write_text(json.dumps(report, indent=2), encoding="utf-8")
    out_summary.write_text(_render_summary(report), encoding="utf-8")
    return report


def _fmt(value: float) -> str:
    if value is None:
        return "n/a"
    if not np.isfinite(value):
        return "inf"
    return f"{value:.4g}"


