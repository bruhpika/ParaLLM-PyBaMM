def parse_logspace(spec: str) -> np.ndarray:
    """Parse a deterministic ``logspace(start, stop, n)`` config string."""
    text = str(spec).strip()
    if not (text.startswith("logspace(") and text.endswith(")")):
        raise ValueError(f"expected 'logspace(start, stop, n)', got {spec!r}")
    parts = [p.strip() for p in text[len("logspace(") : -1].split(",")]
    if len(parts) != 3:
        raise ValueError(f"logspace needs 3 arguments, got {spec!r}")
    start, stop = float(parts[0]), float(parts[1])
    n = int(parts[2])
    if n < 1:
        raise ValueError(f"logspace n must be >= 1, got {n}")
    return np.logspace(start, stop, n)


def voltage_query_times(t_end_s: float, n_points: int, t_start_s: float) -> np.ndarray:
    """Sampling grid for a galvanostatic voltage curve (committed convention)."""
    if t_end_s <= t_start_s:
        raise ValueError(f"t_end_s ({t_end_s}) must exceed t_start_s ({t_start_s})")
    if n_points < 2:
        raise ValueError("n_points must be >= 2")
    return np.linspace(float(t_start_s), float(t_end_s), int(n_points))


def characteristic_scale(y0: Any, convention: str) -> float:
    """Characteristic magnitude used to non-dimensionalize an observable."""
    array = np.asarray(y0, dtype=float).reshape(-1)
    if array.size == 0:
        raise ValueError("empty observable vector")
    if convention == "std":
        value = float(np.std(array))
    elif convention == "mean_magnitude":
        value = float(np.mean(np.abs(array)))
    else:
        raise ValueError(f"unknown normalization convention {convention!r}")
    if not np.isfinite(value) or value <= 1e-12:
        raise ValueError(
            "observable has no resolvable variation at the baseline point "
            f"(scale={value!r}); refusing to normalize by a near-zero scale"
        )
    return value


def mean_abs_normalized_sensitivity(
    jacobian: np.ndarray, x: np.ndarray, y_scale: float
) -> float:
    """Mean |S| over the observation points for the (single) study parameter."""
    scaled = normalized_sensitivity(jacobian, np.asarray(x, dtype=float), y_scale)
    if scaled.size == 0:
        raise ValueError("empty sensitivity block")
    return float(np.abs(scaled).mean())


def implied_relative_standard_error(fim: np.ndarray) -> float:
    """FIM-implied relative standard error of a unit-mean scale factor.

    The FIM must be built from **raw** sensitivities (observable units per unit
    scale factor) with the noise in the same observable units
    (:data:`_block`'s convention since the 2026-11-27 correction); then the
    Cramér–Rao bound gives ``SE = 1/sqrt(FIM)`` in scale-factor units, which
    for ``x = 1`` is also the relative standard error. ``inf`` means no
    information.
    """
    fim = np.asarray(fim, dtype=float)
    if fim.ndim != 2 or fim.shape[0] != fim.shape[1]:
        raise ValueError(f"FIM must be square, got {fim.shape}")
    if fim.shape != (1, 1):
        raise ValueError("relative standard error is defined here for one parameter")
    value = float(fim[0, 0])
    if value <= 0 or not np.isfinite(value):
        return float("inf")
    return float(1.0 / np.sqrt(value))


def classify_observability(mean_abs_s: float, rel_std: float) -> str:
    """Apply the recorded observability rules to one diagnostic block.

    A block is OBSERVABLE only when the recorded mean-|S| rule **and** the
    recorded relative-std rule are both satisfied; either failure means the
    observation set does not pin the parameter well enough to say otherwise.
    """
    if not np.isfinite(mean_abs_s):
        return "UNOBSERVABLE"
    if mean_abs_s < SENSITIVITY_OBSERVABILITY_THRESHOLD:
        return "UNOBSERVABLE"
    if not np.isfinite(rel_std) or rel_std > RELATIVE_STD_OBSERVABILITY_THRESHOLD:
        return "UNOBSERVABLE"
    return "OBSERVABLE"


def classify_information(rel_std: float, strongest_mean_abs_s: float) -> str:
    """Apply a conservative conjunction of the recorded observability rules.

    Two recorded rules exist: the per-protocol mean |S| rule
    (:data:`SENSITIVITY_OBSERVABILITY_THRESHOLD`) and the bootstrap relative
    standard-error rule (:data:`RELATIVE_STD_OBSERVABILITY_THRESHOLD`). The
    per-protocol rule does not aggregate meaningfully across observables with
    different units and noise levels, so for a *combined* observation set we
    require **both**:

    * the combined FIM's implied relative standard error meets the recorded
      information threshold, and
    * at least one contributing observable individually clears the recorded
      mean-|S| threshold.

    This aggregation is declared before looking at the numbers and can only
    make a verdict flip harder, never easier: stacking low-sensitivity
    observables cannot turn UNOBSERVABLE into OBSERVABLE on its own.
    """
    if not np.isfinite(rel_std) or rel_std > RELATIVE_STD_OBSERVABILITY_THRESHOLD:
        return "UNOBSERVABLE"
    if not np.isfinite(strongest_mean_abs_s):
        return "UNOBSERVABLE"
    if strongest_mean_abs_s < SENSITIVITY_OBSERVABILITY_THRESHOLD:
        return "UNOBSERVABLE"
    return "OBSERVABLE"


def compare_voltage_block_to_baseline(
    reproduced: float, baseline: float, tolerance: float
) -> dict[str, Any]:
    """Check that this study reproduces a committed voltage-only value."""
    delta = float(reproduced) - float(baseline)
    return {
        "reproduced_mean_abs_normalized_sensitivity": float(reproduced),
        "baseline_mean_abs_normalized_sensitivity": float(baseline),
        "absolute_delta": delta,
        "tolerance": float(tolerance),
        "within_tolerance": bool(abs(delta) <= float(tolerance)),
    }


def information_ratio(fim_augmented: np.ndarray, fim_voltage_only: np.ndarray) -> float:
    """sqrt(FIM_aug / FIM_vol) = factor by which the standard error shrinks."""
    a = float(np.asarray(fim_augmented, dtype=float).squeeze())
    v = float(np.asarray(fim_voltage_only, dtype=float).squeeze())
    if v <= 0 or not np.isfinite(v):
        return float("inf")
    if a < 0 or not np.isfinite(a):
        return float("inf")
    return float(np.sqrt(a / v))


def standard_error_reduction(reference_relative_se: float, reduced_relative_se: float) -> float:
    """Factor by which a relative standard error shrinks: SE_ref / SE_new.

    ``0`` means the new set carries no information about the parameter
    (``SE_new = inf``); ``inf`` means the reference set had none.
    """
    reference = float(reference_relative_se)
    reduced = float(reduced_relative_se)
    if not np.isfinite(reduced):
        return 0.0
    if not np.isfinite(reference):
        return float("inf")
    if reduced <= 0:
        return float("inf")
    return float(reference / reduced)


def marginal_relative_standard_errors(fim: np.ndarray) -> np.ndarray:
    """Cramér–Rao marginal relative SEs for unit-mean scale factors.

    The FIM must already be expressed in dimensionless sensitivities
    (:func:`normalized_sensitivity` with ``x = 1``). The marginal variance of
    parameter ``j`` is ``pinv(FIM)[j, j]``.

    A rank-deficient FIM means at least one parameter combination is not
    constrained at all. In that case the pseudo-inverse can return a
    misleadingly small diagonal (the minimum-norm solution), so every entry is
    returned as ``inf``. Reporting a finite SE for a non-identifiable parameter
    would be exactly the failure mode rules 7 and 8 warn about.
    """
    fim = np.asarray(fim, dtype=float)
    if fim.ndim != 2 or fim.shape[0] != fim.shape[1]:
        raise ValueError(f"FIM must be square, got {fim.shape}")
    n = fim.shape[0]
    if np.linalg.matrix_rank(fim) < n:
        return np.full(n, np.inf, dtype=float)
    covariance = np.linalg.pinv(fim)
    diagonal = np.clip(np.diag(covariance), 0.0, None)
    with np.errstate(divide="ignore", invalid="ignore"):
        return np.where(diagonal > 0, np.sqrt(diagonal), np.inf)


def parameter_correlation_matrix(fim: np.ndarray) -> np.ndarray:
    """Parameter correlation matrix implied by a (dimensionless) FIM."""
    fim = np.asarray(fim, dtype=float)
    if fim.ndim != 2 or fim.shape[0] != fim.shape[1]:
        raise ValueError(f"FIM must be square, got {fim.shape}")
    covariance = np.linalg.pinv(fim)
    scale = np.sqrt(np.clip(np.diag(covariance), 0.0, None))
    with np.errstate(divide="ignore", invalid="ignore"):
        corr = covariance / np.outer(scale, scale)
    corr = np.nan_to_num(corr, nan=0.0, posinf=0.0, neginf=0.0)
    np.fill_diagonal(corr, 1.0)
    return corr


def variance_inflation_factor(joint_relative_se: float, single_relative_se: float) -> float:
    """Variance cost of freeing the other parameters: (SE_joint / SE_single)^2.

    ``1`` means the other parameters cost nothing; ``>1`` means the joint fit
    inflates the variance of this parameter; ``inf`` means it is not
    identifiable in the joint fit.
    """
    joint = float(joint_relative_se)
    single = float(single_relative_se)
    if not np.isfinite(single) or single <= 0:
        return float("inf")
    if not np.isfinite(joint):
        return float("inf")
    return float((joint / single) ** 2)


def diffusion_frequency(diffusivity: float, particle_radius: float) -> dict[str, Any]:
    """A-priori solid-diffusion time constant and characteristic frequency.

    Pure arithmetic on two values read from the installed parameter set; no
    value is invented. ``tau = R^2 / D`` and ``f = 1 / (2*pi*tau)`` are the
    standard spherical-diffusion scales used to choose an EIS band *before*
    looking at any sensitivity.
    """
    if diffusivity <= 0 or particle_radius <= 0:
        raise ValueError("diffusivity and particle_radius must be positive")
    tau = float(particle_radius) ** 2 / float(diffusivity)
    return {
        "diffusivity_m2_s": float(diffusivity),
        "particle_radius_m": float(particle_radius),
        "diffusion_time_constant_s": tau,
        "diffusion_frequency_Hz": 1.0 / (2.0 * np.pi * tau),
    }


def gitt_feature_sigmas(gitt_spec: dict[str, Any], sigma_V: float) -> dict[str, dict[str, Any]]:
    """Propagate raw voltage noise into the declared GITT feature noises.

    Pure error propagation for independent per-sample voltage noise
    ``sigma_V`` (2026-11-27 unit correction: the derived features must carry
    noise in their own units, not the raw voltage noise):

    * end-of-rest voltage: single sample -> ``sigma_V``;
    * pulse voltage drop: difference of the first and last pulse samples ->
      ``sqrt(2) * sigma_V``;
    * sqrt(t) relaxation slope: ordinary least-squares slope of voltage
      against ``sqrt(t)`` over the declared fit window -> ``sigma_V /
      sqrt(Sxx)`` with ``Sxx = sum((sqrt(t_i) - mean)^2)`` in s.

    The slope's noise has units V/sqrt(s); reporting it as a voltage was the
    second half of the same unit mismatch that scaled the implied standard
    errors.
    """
    sigma = float(sigma_V)
    if sigma <= 0:
        raise ValueError(f"sigma_V must be positive, got {sigma!r}")
    period = float(gitt_spec["period_s"])
    if period <= 0:
        raise ValueError(f"period_s must be positive, got {period!r}")
    n_fit = int(gitt_spec.get("relaxation_fit_points", 5))
    if n_fit < 3:
        raise ValueError(f"relaxation_fit_points must be >= 3, got {n_fit}")
    sqrt_t = np.sqrt(np.arange(n_fit, dtype=float) * period)
    sxx = float(np.sum((sqrt_t - sqrt_t.mean()) ** 2))
    if sxx <= 0:
        raise ValueError("degenerate sqrt(t) fit window (Sxx <= 0)")
    slope_sigma = sigma / np.sqrt(sxx)
    return {
        "gitt_rest_voltage": {
            "sigma": sigma,
            "units": "V",
            "derivation": "end-of-rest voltage is one sampled voltage",
        },
        "gitt_pulse_drop": {
            "sigma": float(np.sqrt(2.0) * sigma),
            "units": "V",
            "derivation": "pulse drop is a difference of two samples",
        },
        "gitt_relaxation_slope": {
            "sigma": float(slope_sigma),
            "units": "V.s-0.5",
            "derivation": (
                f"OLS slope against sqrt(t) over {n_fit} samples at {period:g} s: "
                f"sigma_V/sqrt(Sxx), Sxx={sxx:.4g} s"
            ),
        },
    }


def gitt_protocol_warnings(spec: dict[str, Any]) -> list[str]:
    """Flag GITT protocols whose null result would be uninformative.

    PyBaMM starts at 100% SOC when ``initial_soc`` is null. At the top of
    charge the graphite OCP is flat, so a diffusivity perturbation barely
    moves the voltage; a low signal there is a protocol artefact, not evidence
    that GITT cannot observe transport. The 2026-11-27 correction exists
    because this guard was missing from the first committed run.
    """
    warnings: list[str] = []
    soc = spec.get("initial_soc")
    if soc is None:
        warnings.append(
            "GITT initial_soc is null: PyBaMM starts at 100% SOC, where the "
            "graphite OCP is flat. A low GITT signal under this protocol is "
            "not evidence about transport observability."
        )
    elif float(soc) > 0.9:
        warnings.append(
            f"GITT initial_soc={float(soc):.2f} is near full charge, where the "
            "graphite OCP is flat; a low GITT signal is protocol-dependent."
        )
    return warnings


def relative_change(reference: Any, perturbed: Any) -> float:
    """max|Δ| / max|reference| for two equal-length vectors."""
    a = np.asarray(reference, dtype=float).reshape(-1)
    b = np.asarray(perturbed, dtype=float).reshape(-1)
    if a.shape != b.shape:
        raise ValueError(f"shape mismatch: {a.shape} vs {b.shape}")
    peak = float(np.max(np.abs(a)))
    if peak <= 0:
        return float("inf")
    return float(np.max(np.abs(b - a)) / peak)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 16), b""):
            digest.update(chunk)
    return digest.hexdigest()


