def scaled_parameter_values(parameter_set: str, parameter: str, factor: float):
    """Installed parameter set with one study parameter multiplied by ``factor``.

    In-memory study device only: the original reported value is never written
    to any persistent store (same convention as the committed feasibility
    study). Scalar parameters are scaled directly; callables are wrapped.
    """
    import pybamm

    pv = pybamm.ParameterValues(parameter_set)
    value = pv[parameter]
    if callable(value):
        original = value

        def scaled(*args, _orig=original, _f=factor):
            return _f * _orig(*args)

        pv.update({parameter: scaled})
    else:
        pv.update({parameter: float(value) * factor})
    return pv


def voltage_curve(pv: Any, model_name: str, steps: list[str], t_query: np.ndarray) -> np.ndarray:
    import pybamm

    model = getattr(pybamm.lithium_ion, model_name)()
    experiment = pybamm.Experiment(list(steps))
    solution = pybamm.Simulation(model, parameter_values=pv, experiment=experiment).solve()
    return np.asarray(solution["Terminal voltage [V]"](t=t_query), dtype=float)


def _gitt_result(pv: Any, spec: dict[str, Any]):
    return run_gitt_d(
        pv,
        current_A=float(spec["current_A"]),
        pulse_duration_s=float(spec["pulse_duration_s"]),
        rest_duration_s=float(spec["rest_duration_s"]),
        n_pulses=int(spec["n_pulses"]),
        period_s=float(spec["period_s"]),
        model_name=str(spec["model_name"]),
        initial_soc=spec.get("initial_soc"),
    )


def gitt_rest_voltages(pv: Any, spec: dict[str, Any]) -> np.ndarray:
    """End-of-rest voltage at each titration (quasi-relaxed GITT-D points)."""
    result = _gitt_result(pv, spec)
    phases = np.asarray(result.phase)
    indices = np.asarray(result.titration_index)
    values: list[float] = []
    for index in range(int(spec["n_pulses"])):
        mask = (indices == index) & (phases == "rest")
        if not mask.any():
            raise RuntimeError(f"no rest samples for GITT titration {index}")
        values.append(float(result.voltage_V[mask][-1]))
    return np.asarray(values, dtype=float)


def gitt_pulse_drops(pv: Any, spec: dict[str, Any]) -> np.ndarray:
    """Voltage drop across each discharge pulse (pulse overpotential)."""
    result = _gitt_result(pv, spec)
    phases = np.asarray(result.phase)
    indices = np.asarray(result.titration_index)
    drops: list[float] = []
    for index in range(int(spec["n_pulses"])):
        mask = (indices == index) & (phases == "pulse")
        if mask.sum() < 2:
            raise RuntimeError(f"fewer than 2 pulse samples for GITT titration {index}")
        pulse = result.voltage_V[mask]
        drops.append(float(pulse[0] - pulse[-1]))
    return np.asarray(drops, dtype=float)


def eis_spectrum(pv: Any, spec: dict[str, Any], component: str) -> np.ndarray:
    """EIS spectrum component: 'z_re' or 'neg_z_im' (storage convention)."""
    frequencies = parse_logspace(str(spec["frequencies_Hz"]))
    result = compute_eis(
        str(spec["model_name"]),
        pv,
        frequencies,
        initial_soc=spec.get("initial_soc"),
    )
    if component == "z_re":
        return np.asarray(result.z_re_Ohm, dtype=float)
    if component == "neg_z_im":
        return -np.asarray(result.z_im_Ohm, dtype=float)
    raise ValueError(f"unknown EIS component {component!r}")


def ocv_curve(pv: Any, spec: dict[str, Any]) -> np.ndarray:
    soc = np.linspace(0.0, 1.0, int(spec["n_points"]))
    result = compute_ocv_vs_soc(pv, soc, direction=spec.get("direction"))
    return np.asarray(result.ocv_V, dtype=float)


def _jacobian_for(
    predict_of_pv: Callable[[Any], np.ndarray],
    parameter_set: str,
    parameter: str,
    rel_step: float,
    x: np.ndarray,
    normalization: str,
) -> tuple[np.ndarray, float]:
    """Finite-difference Jacobian of a PV-based observable w.r.t. the scale factor."""

    def predict(xs: np.ndarray) -> np.ndarray:
        pv = scaled_parameter_values(parameter_set, parameter, float(xs[0]))
        return predict_of_pv(pv)

    y0 = np.asarray(predict(x), dtype=float).reshape(-1)
    y_scale = characteristic_scale(y0, normalization)
    jacobian = finite_difference_jacobian(predict, x, rel_step=rel_step)
    return jacobian, y_scale


def _block(
    name: str,
    jacobian: np.ndarray,
    y_scale: float,
    sigma: float,
    x: np.ndarray,
    normalization: str,
) -> dict[str, Any]:
    block = {
        "jacobian": jacobian,
        "sigma": float(sigma),
        "y_scale": float(y_scale),
    }
    mean_abs_s = mean_abs_normalized_sensitivity(jacobian, x, y_scale)
    fim = multi_observable_fim({name: block}, x)
    rel_std = implied_relative_standard_error(fim["fim"])
    return {
        "name": name,
        "normalization": normalization,
        "sigma": float(sigma),
        "y_scale": float(y_scale),
        "n_points": int(jacobian.shape[0]),
        "mean_abs_normalized_sensitivity": mean_abs_s,
        "fim": float(np.asarray(fim["fim"]).squeeze()),
        "implied_relative_standard_error": rel_std,
        "classification": classify_observability(mean_abs_s, rel_std),
        "_block": block,
    }


def run_diagnostic(config_path: Path) -> dict[str, Any]:
    """Run the full diagnostic and write the committed artifacts."""
    import pybamm

    if pybamm.__version__ != PINNED_PYBAM_VERSION:
        raise RuntimeError(
            f"pinned pybamm {PINNED_PYBAM_VERSION} required, found {pybamm.__version__}"
        )

    cfg = load_config(config_path)
    rel = float(cfg["rel_perturbation"])
    if rel <= 0 or not np.isfinite(rel):
        raise ValueError(f"rel_perturbation must be finite and positive, got {rel!r}")

    parameter_set = str(cfg["parameter_set"])
    parameter = str(cfg["parameter"])
    model_name = str(cfg["model_name"])
    norms = cfg["normalization"]
    x = np.array([1.0])

    # Introspection guard: the study parameter must exist in the installed set.
    pv0 = pybamm.ParameterValues(parameter_set)
    if parameter not in pv0.keys():
        raise KeyError(
            f"study parameter {parameter!r} is not in the installed {parameter_set} set; "
            "refusing to invent or substitute a value"
        )
    baseline_value = pv0[parameter]
    if callable(baseline_value):
        raise TypeError(
            f"study parameter {parameter!r} is function-valued in {parameter_set}; "
            "this diagnostic expects a scalar (see configs/p2/diffusivity_feasibility.yaml)"
        )

    radius_key = "Negative particle radius [m]"
    if radius_key not in pv0.keys():
        raise KeyError(f"required verified key {radius_key!r} is absent")
    a_priori = diffusion_frequency(float(baseline_value), float(pv0[radius_key]))
    eis_band = parse_logspace(str(cfg["eis"]["frequencies_Hz"]))
    a_priori["eis_band_Hz"] = [float(eis_band.min()), float(eis_band.max())]
    a_priori["eis_band_covers_diffusion_frequency"] = bool(
        eis_band.min() <= a_priori["diffusion_frequency_Hz"] <= eis_band.max()
    )
    a_priori["source"] = (
        "installed Chen2020 values; tau = R^2/D, f = 1/(2*pi*tau)"
    )

    out_report = REPO_ROOT / str(cfg["outputs"]["report"])
    out_summary = REPO_ROOT / str(cfg["outputs"]["summary"])
    out_report.parent.mkdir(parents=True, exist_ok=True)

    t0 = time.perf_counter()
    blocks: dict[str, dict[str, Any]] = {}
    voltage_only: dict[str, dict[str, Any]] = {}

    # ---- voltage block: identical protocols/grids to the committed study ----
    for cond in cfg["voltage_conditions"]:
        name = f"voltage_{cond['name']}"
        t_query = voltage_query_times(
            float(cond["t_end_s"]),
            int(cfg["voltage_n_points"]),
            float(cfg["voltage_t_start_s"]),
        )
        jac, y_scale = _jacobian_for(
            lambda pv, steps=cond["steps"], t=t_query: voltage_curve(
                pv, model_name, steps, t
            ),
            parameter_set,
            parameter,
            rel,
            x,
            str(norms["voltage"]),
        )
        block = _block(
            name,
            jac,
            y_scale,
            float(cfg["noise"]["voltage_V"]),
            x,
            str(norms["voltage"]),
        )
        blocks[name] = block
        voltage_only[name] = block

    # ---- GITT-D blocks ----------------------------------------------------
    gitt_spec = cfg["gitt_d"]
    jac, y_scale = _jacobian_for(
        lambda pv, spec=gitt_spec: gitt_rest_voltages(pv, spec),
        parameter_set,
        parameter,
        rel,
        x,
        str(norms["gitt_rest_voltage"]),
    )
    blocks["gitt_d_rest_voltage"] = _block(
        "gitt_d_rest_voltage",
        jac,
        y_scale,
        float(cfg["noise"]["gitt_voltage_V"]),
        x,
        str(norms["gitt_rest_voltage"]),
    )

    jac, y_scale = _jacobian_for(
        lambda pv, spec=gitt_spec: gitt_pulse_drops(pv, spec),
        parameter_set,
        parameter,
        rel,
        x,
        str(norms["gitt_pulse_drop"]),
    )
    blocks["gitt_d_pulse_drop"] = _block(
        "gitt_d_pulse_drop",
        jac,
        y_scale,
        float(cfg["noise"]["gitt_voltage_V"]),
        x,
        str(norms["gitt_pulse_drop"]),
    )

    # ---- EIS blocks -------------------------------------------------------
    eis_spec = cfg["eis"]
    pv_eis = scaled_parameter_values(parameter_set, parameter, 1.0)
    eis_reference = eis_spectrum(pv_eis, eis_spec, "z_re")
    eis_sigma = float(cfg["noise"]["eis_relative"]) * float(
        np.mean(np.abs(eis_reference))
    )
    if eis_sigma <= 0:
        raise ValueError(
            "EIS noise assumption resolves to a non-positive sigma; refusing to continue"
        )
    for name, component in (
        ("eis_re_impedance", "z_re"),
        ("eis_neg_im_impedance", "neg_z_im"),
    ):
        jac, y_scale = _jacobian_for(
            lambda pv, spec=eis_spec, comp=component: eis_spectrum(pv, spec, comp),
            parameter_set,
            parameter,
            rel,
            x,
            str(norms["eis"]),
        )
        blocks[name] = _block(
            name, jac, y_scale, eis_sigma, x, str(norms["eis"])
        )

    # ---- OCV-vs-SOC null control -----------------------------------------
    ocv_spec = cfg["ocv_soc"]
    jac, y_scale = _jacobian_for(
        lambda pv, spec=ocv_spec: ocv_curve(pv, spec),
        parameter_set,
        parameter,
        rel,
        x,
        str(norms["ocv"]),
    )
    blocks["ocv_soc_control"] = _block(
        "ocv_soc_control",
        jac,
        y_scale,
        float(cfg["noise"]["ocv_voltage_V"]),
        x,
        str(norms["ocv"]),
    )

    # ---- EIS propagation positive control --------------------------------
    control = cfg["positive_control"]
    control_parameter = str(control["parameter"])
    control_factor = float(control["factor"])
    if control_parameter not in pv0.keys():
        raise KeyError(
            f"positive-control parameter {control_parameter!r} is absent from {parameter_set}"
        )
    control_component = str(control["component"])
    base_spectrum = eis_spectrum(
        scaled_parameter_values(parameter_set, parameter, 1.0), eis_spec, control_component
    )
    control_spectrum = eis_spectrum(
        scaled_parameter_values(parameter_set, control_parameter, control_factor),
        eis_spec,
        control_component,
    )
    positive_control = {
        "parameter": control_parameter,
        "factor": control_factor,
        "component": control_component,
        "relative_impedance_change": relative_change(base_spectrum, control_spectrum),
        "interpretation": (
            "A non-zero relative change proves the EIS simulation applies supplied "
            "parameter values. A near-zero change for the study parameter is therefore "
            "a property of the installed EIS formulation, not a harness bug."
        ),
    }

    # ---- combine ----------------------------------------------------------
    def _combine(names: list[str]) -> dict[str, Any]:
        combined = multi_observable_fim(
            {n: blocks[n]["_block"] for n in names}, x
        )
        fim = np.asarray(combined["fim"], dtype=float)
        rel_std = implied_relative_standard_error(fim)
        mean_abs = {n: blocks[n]["mean_abs_normalized_sensitivity"] for n in names}
        strongest = float(max(mean_abs.values()))
        # The stacked mean |S| uses each block's own normalization, so the
        # combined verdict requires the combined information rule *and* at
        # least one block clearing the recorded per-observable sensitivity
        # rule. Stacking cannot manufacture a flip by itself.
        return {
            "observables": names,
            "fim": float(fim.squeeze()),
            "implied_relative_standard_error": rel_std,
            "classification": classify_information(rel_std, strongest),
            "strongest_block_mean_abs_normalized_sensitivity": strongest,
            "classification_rule": (
                "conjunction: combined implied rel. SE <= "
                f"{RELATIVE_STD_OBSERVABILITY_THRESHOLD} AND strongest block mean |S| >= "
                f"{SENSITIVITY_OBSERVABILITY_THRESHOLD}"
            ),
            "per_block_mean_abs_normalized_sensitivity": mean_abs,
            "condition_number": combined["condition_number"],
            "stacked_jacobian_shape": combined["stacked_jacobian_shape"],
        }

    voltage_names = list(voltage_only)
    augmented_names = voltage_names + [
        "gitt_d_rest_voltage",
        "gitt_d_pulse_drop",
        "eis_re_impedance",
        "eis_neg_im_impedance",
    ]
    comparison = _combine(voltage_names)
    augmented = _combine(augmented_names)

    # ---- reproduce the committed voltage-only baseline -------------------
    baseline_path = REPO_ROOT / str(cfg["baseline_report"])
    baseline_block: dict[str, Any] = {
        "path": str(cfg["baseline_report"]),
        "source": None,
    }
    if baseline_path.exists():
        baseline = json.loads(baseline_path.read_text(encoding="utf-8"))
        tolerance = float(cfg["baseline_tolerance"])
        checks: dict[str, Any] = {}
        within = True
        for cond in cfg["voltage_conditions"]:
            key = cond["name"]
            committed = (
                baseline.get("per_condition", {})
                .get(key, {})
                .get("mean_abs_normalized_sensitivity", {})
                .get(parameter)
            )
            if committed is None:
                checks[key] = {
                    "status": "missing committed value",
                    "parameter": parameter,
                }
                within = False
                continue
            check = compare_voltage_block_to_baseline(
                blocks[f"voltage_{key}"]["mean_abs_normalized_sensitivity"],
                float(committed),
                tolerance,
            )
            checks[key] = check
            within = within and check["within_tolerance"]
        baseline_block.update(
            {
                "source": "results/p2/diffusivity_feasibility/report.json",
                "parameter": parameter,
                "checks": checks,
                "all_within_tolerance": within,
            }
        )
    else:
        baseline_block["note"] = (
            "committed baseline report absent; comparison skipped (not an error)"
        )

    information_gain = information_ratio(augmented["fim"], comparison["fim"])

    flipped = (
        comparison["classification"] == "UNOBSERVABLE"
        and augmented["classification"] == "OBSERVABLE"
    )
    if flipped:
        verdict_statement = (
            "The added observables flip the recorded UNOBSERVABLE verdict for this "
            "parameter under the declared aggregation rule."
        )
    else:
        verdict_statement = (
            "The added observables do NOT flip the recorded UNOBSERVABLE verdict "
            "under the declared aggregation rule; the parameter remains MEASURE, "
            "not CALIBRATE."
        )
    verdict = {
        "voltage_only_classification": comparison["classification"],
        "observable_augmented_classification": augmented["classification"],
        "flip": bool(flipped),
        "statement": verdict_statement,
        "decision": "unchanged",
    }

    report: dict[str, Any] = {
        "label": "SYNTHETIC OBSERVABLE-AUGMENTED IDENTIFIABILITY DIAGNOSTIC",
        "run_id": cfg["run_id"],
        "description": cfg.get("description", ""),
        "diagnostic_only": True,
        "decision_changed": False,
        "registry_write": False,
        "parameter": parameter,
        "parameter_set": parameter_set,
        "model_name": model_name,
        "baseline_parameter_value": float(baseline_value),
        "scale_factor": float(x[0]),
        "rel_perturbation": rel,
        "thresholds": {
            "sensitivity_observability": SENSITIVITY_OBSERVABILITY_THRESHOLD,
            "relative_std_observability": RELATIVE_STD_OBSERVABILITY_THRESHOLD,
            "source": "src/pybamm_closed_loop/assembly/observability.py (recorded rules)",
        },
        "a_priori_diffusion_scales": a_priori,
        "per_observable": {
            name: {k: v for k, v in block.items() if k != "_block"}
            for name, block in blocks.items()
        },
        "voltage_only": comparison,
        "observable_augmented": augmented,
        "information_gain_sqrt_ratio": information_gain,
        "standard_error_reduction_factor": information_gain,
        "verdict": verdict,
        "eis_positive_control": positive_control,
        "baseline_comparison": baseline_block,
        "environment": {
            "python": platform.python_version(),
            "pybamm": pybamm.__version__,
        },
        "verified_api_signatures": verified_api_signatures(),
        "config_sha256": _sha256(Path(config_path)),
        "limitations": LIMITATIONS,
        "scientific_note": (
            "Local sensitivity diagnostic only. A well-conditioned FIM is not proof "
            "of identifiability (rule 7) and all curves are synthetic (rule 8). No "
            "calibration objective, registry record or dossier decision was changed."
        ),
        "runtime_s": time.perf_counter() - t0,
    }

    out_report.write_text(json.dumps(report, indent=2), encoding="utf-8")
    out_summary.write_text(_render_summary(report), encoding="utf-8")
    return report


def _fmt(value: float) -> str:
    if value is None:
        return "n/a"
    if not np.isfinite(value):
        return "inf"
    return f"{value:.4g}"


def _render_summary(report: dict[str, Any]) -> str:
    lines: list[str] = []
    lines.append("# Observable-augmented observability diagnostic")
    lines.append("")
    lines.append(
        f"**{report['label']}** — diagnostic only; no parameter decision changed."
    )
    lines.append("")
    lines.append(
        f"Parameter: `{report['parameter']}` · parameter set `{report['parameter_set']}` "
        f"· model `{report['model_name']}` · scale factor {report['scale_factor']}"
    )
    lines.append("")
    apriori = report["a_priori_diffusion_scales"]
    lines.append("## A-priori diffusion scales (choose the EIS band before scoring)")
    lines.append("")
    lines.append(
        f"- D = {_fmt(apriori['diffusivity_m2_s'])} m²/s, "
        f"R = {_fmt(apriori['particle_radius_m'])} m"
    )
    lines.append(
        f"- τ = R²/D = {_fmt(apriori['diffusion_time_constant_s'])} s → "
        f"f_diff = {_fmt(apriori['diffusion_frequency_Hz'])} Hz"
    )
    lines.append(
        f"- EIS band {_fmt(apriori['eis_band_Hz'][0])}–{_fmt(apriori['eis_band_Hz'][1])} Hz "
        f"covers f_diff: **{apriori['eis_band_covers_diffusion_frequency']}**"
    )
    lines.append("")
    lines.append("## Per observable")
    lines.append("")
    lines.append(
        "| observable | n | norm | sigma | mean \\|S\\| | implied rel. SE | classification |"
    )
    lines.append("|---|---:|---|---:|---:|---:|---|")
    for name, block in report["per_observable"].items():
        lines.append(
            f"| {name} | {block['n_points']} | {block['normalization']} | "
            f"{_fmt(block['sigma'])} | "
            f"{_fmt(block['mean_abs_normalized_sensitivity'])} | "
            f"{_fmt(block['implied_relative_standard_error'])} | "
            f"{block['classification']} |"
        )
    lines.append("")
    lines.append("## Observable sets")
    lines.append("")
    lines.append("| set | FIM | implied rel. SE | strongest block mean \\|S\\| | classification |")
    lines.append("|---|---:|---:|---:|---|")
    for key, label in (
        ("voltage_only", "voltage only"),
        ("observable_augmented", "voltage + GITT-D + EIS"),
    ):
        set_block = report[key]
        lines.append(
            f"| {label} | {_fmt(set_block['fim'])} | "
            f"{_fmt(set_block['implied_relative_standard_error'])} | "
            f"{_fmt(set_block['strongest_block_mean_abs_normalized_sensitivity'])} | "
            f"{set_block['classification']} |"
        )
    lines.append("")
    lines.append(
        "Combined-set rule (declared before scoring): "
        f"{report['voltage_only']['classification_rule']}. "
        "Stacking observables can therefore only make a flip harder, never "
        "manufacture one."
    )
    lines.append("")
    lines.append(
        f"Information gain (sqrt FIM ratio = standard-error reduction factor): "
        f"**{_fmt(report['information_gain_sqrt_ratio'])}**"
    )
    lines.append("")
    verdict = report["verdict"]
    lines.append("## Verdict")
    lines.append("")
    lines.append(
        f"- voltage only: **{verdict['voltage_only_classification']}**"
    )
    lines.append(
        f"- voltage + GITT-D + EIS: **{verdict['observable_augmented_classification']}**"
    )
    lines.append(f"- verdict flip: **{verdict['flip']}** — {verdict['statement']}")
    lines.append(f"- parameter decision: **{verdict['decision']}**")
    lines.append("")
    control = report["eis_positive_control"]
    lines.append("## EIS propagation positive control")
    lines.append("")
    lines.append(
        f"Scaling `{control['parameter']}` by {control['factor']:g} changes the "
        f"{control['component']} spectrum by "
        f"**{_fmt(control['relative_impedance_change'])}** (relative). "
        f"{control['interpretation']}"
    )
    lines.append("")
    if "checks" in report["baseline_comparison"]:
        lines.append("## Reproduction of the committed voltage-only baseline")
        lines.append("")
        lines.append("| condition | reproduced | committed | |Δ| | within tolerance |")
        lines.append("|---|---:|---:|---:|---|")
        for name, check in report["baseline_comparison"]["checks"].items():
            if "reproduced_mean_abs_normalized_sensitivity" not in check:
                lines.append(f"| {name} | — | — | — | {check['status']} |")
                continue
            lines.append(
                f"| {name} | "
                f"{_fmt(check['reproduced_mean_abs_normalized_sensitivity'])} | "
                f"{_fmt(check['baseline_mean_abs_normalized_sensitivity'])} | "
                f"{_fmt(abs(check['absolute_delta']))} | "
                f"{'yes' if check['within_tolerance'] else 'no'} |"
            )
        lines.append("")
    lines.append("## Limitations")
    lines.append("")
    for item in report["limitations"]:
        lines.append(f"- {item}")
    lines.append("")
    lines.append(
        "A successful local FIM is **not** proof of parameter identifiability "
        "(scientific rule 7), and synthetic curves are **not** experimental "
        "validation (rule 8)."
    )
    lines.append("")
    return "\n".join(lines)


